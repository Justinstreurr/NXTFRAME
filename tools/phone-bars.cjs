// Samples the top colour of every phone screenshot under public/images (files named m-*.webp/png/jpg)
// and writes src/components/phoneBars.ts: per screenshot the colour the status bar above it takes,
// and whether its clock and icons should be dark (on a light bar) or white.
// usage (from the project folder): node tools/phone-bars.cjs .  -- run again after adding phone screenshots
const fs = require("fs");
const path = require("path");
const proj = process.argv[2];
const sharp = require(require.resolve("sharp", { paths: [proj] }));
const pub = path.join(proj, "public");

const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/^m-.*\.(webp|png|jpe?g)$/.test(e.name)) files.push(p);
  }
})(path.join(pub, "images"));

(async () => {
  const rows = [];
  for (const f of files.sort()) {
    const meta = await sharp(f).metadata();
    const { data } = await sharp(f).extract({ left: 0, top: 1, width: meta.width, height: Math.max(2, Math.round(meta.height * 0.004)) }).resize(1, 1).raw().toBuffer({ resolveWithObject: true });
    const [r, g, b] = data;
    const hex = "#" + [r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("");
    const lum = (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
    rows.push(`  "/${path.relative(pub, f).replace(/\\/g, "/")}": { bg: "${hex}", dark: ${lum > 0.6} },`);
  }
  const out = `/* Generated by tools/phone-bars.cjs: the status bar colour above each phone screenshot (its top
   pixel row), and whether the clock and icons on it are dark. Screenshots not listed get a black bar. */
export const phoneBars: Record<string, { bg: string; dark: boolean }> = {
${rows.join("\n")}
};
`;
  fs.writeFileSync(path.join(proj, "src", "components", "phoneBars.ts"), out);
  console.log(`${rows.length} screenshots`);
})();
